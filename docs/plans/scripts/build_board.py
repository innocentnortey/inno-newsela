#!/usr/bin/env python3
"""Build the §7 ticket board and the coverage matrix from the per-ticket files (stdlib only).

    python3 docs/plans/scripts/build_board.py board    # docs/plans/tickets/*.md -> docs/plans/tickets.md
    python3 docs/plans/scripts/build_board.py matrix   # fills the coverage matrix in docs/plans/coverage-audit.md
    python3 docs/plans/scripts/build_board.py gaps     # (req, WF) pairs no ticket AC proves yet

Why: the per-ticket .md files are the source of truth (published verbatim to GitLab); the board and the matrix are
derived so they cannot drift. Matrix rule (to-tickets coverage-audit reference): one row per requirement x workflow in
its *Applies to*; the proof is an AC on the integration owner that names the WF and lists the requirement after
`covers:`; the implementing ticket is the earliest *other* ticket covering that requirement that the owner is blocked
by (else the owner itself).
"""
import json
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[3]
sys.path.insert(0, str(ROOT / ".claude/workflow/to-tickets/scripts"))
import coverage_audit as ca  # noqa: E402

TICKETS = ROOT / "docs/plans/tickets"
BOARD = ROOT / "docs/plans/tickets.md"
AUDIT = ROOT / "docs/plans/coverage-audit.md"
OBS = ROOT / "docs/design/observability.md"
MATRIX_HEAD = "| Req | Workflow | Component / contract | Implementing ticket | Integration owner | Acceptance criterion | Evidence |"
ID_RX = re.compile(r"\b(?:R|GR|CON|CON-G|SCR|EV-R|EV-S|OBS|M)-?\d+\b")


def order_key(p):
    m = re.match(r"([A-Z]+)-(\d+)", p.stem)
    return (0 if m.group(1) == "FW" else 1, int(m.group(2)))


def records():
    out = []
    for p in sorted((q for q in TICKETS.glob("*.json") if not q.name.startswith("probe")), key=order_key):
        out.append(json.loads(p.read_text()))
    return out


def board():
    parts = ["# Ticket board — Newsela Lesson Studio (generated)\n",
             "<!-- Generated by docs/plans/scripts/build_board.py from docs/plans/tickets/*.md; do not edit. "
             "GitLab owns status. -->\n"]
    for r in records():
        md = TICKETS / f"{r['id']}.md"
        parts.append(md.read_text().strip() + "\n")
    BOARD.write_text("\n".join(parts))
    print(f"board: {len(parts) - 2} tickets -> {BOARD.relative_to(ROOT)}")


def covers(ac_text):
    m = re.search(r"covers:\s*(.*)$", ac_text, re.I)
    return set(x.upper() for x in ID_RX.findall(m.group(1))) if m else set()


def load():
    tickets = ca.parse_tickets(BOARD.read_text())
    workflows = ca.parse_workflows([OBS.read_text()])
    audit = AUDIT.read_text()
    reqs, _ = ca.parse_audit(audit)
    return tickets, workflows, audit, reqs


def compute():
    tickets, workflows, audit, reqs = load()
    by_id = {t["id"]: t for t in tickets}
    known = set(by_id)
    order = {t["id"]: i for i, t in enumerate(tickets)}
    acs = {t["id"]: ca.ticket_acs(t)[0] for t in tickets}
    rows, gaps = [], []
    used = {}
    for _, r in reqs:
        rid = ca._plain(r["id"]).upper()
        if not ca._filled(r["id"]):
            continue
        included, _, _, _ = ca._scope(r["applies"], workflows)
        coverers = [t for t in tickets if any(rid in covers(a) for a in acs[t["id"]].values())]
        for wf in sorted(included, key=lambda w: int(w.split("-")[1])):
            proof = None
            cands = [(t["id"], acid) for t in coverers for acid, text in acs[t["id"]].items()
                     if rid in covers(text) and re.search(rf"\b{wf}\b", text.upper())]
            fresh = [c for c in cands if used.get((rid,) + c, wf) == wf]
            if fresh:
                proof = fresh[0]
                used[(rid,) + proof] = wf
            if not proof:
                gaps.append((rid, wf))
                continue
            owner = proof[0]
            blocked = ca.blockers(by_id[owner], known) or set()
            impl = next((t["id"] for t in sorted(coverers, key=lambda t: order[t["id"]])
                         if t["id"] != owner and t["id"] in blocked), owner)
            comp = (r["text"][:70] + "…") if len(r["text"]) > 70 else r["text"]
            comp = comp.replace("|", "/")
            rows.append(f"| {rid} | {wf} | {comp} | {impl} | {owner} | {owner} {proof[1]} | "
                        f"planned: {owner} {proof[1]} (filled `verified:` at §8) |")
    return rows, gaps, audit


def matrix():
    rows, gaps, audit = compute()
    lines = audit.split("\n")
    start = next(i for i, l in enumerate(lines) if l.startswith("| Req | Workflow"))
    end = start + 2
    while end < len(lines) and lines[end].startswith("|"):
        end += 1
    new = lines[:start] + [MATRIX_HEAD, "|---|---|---|---|---|---|---|"] + rows + lines[end:]
    AUDIT.write_text("\n".join(new))
    print(f"matrix: {len(rows)} rows; {len(gaps)} (req, WF) pairs without a proving AC")


def show_gaps():
    _, gaps, _ = compute()
    for rid, wf in gaps:
        print(rid, wf)
    print(f"{len(gaps)} gaps")


if __name__ == "__main__":
    {"board": board, "matrix": matrix, "gaps": show_gaps}[sys.argv[1]]()
