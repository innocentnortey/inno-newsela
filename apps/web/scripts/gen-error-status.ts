import { readFileSync, writeFileSync } from "node:fs";
import { fileURLToPath, pathToFileURL } from "node:url";
import { parse } from "yaml";

interface CatalogEntry {
  status?: unknown;
  retry_after?: unknown;
}

export function render_error_status(catalog_yaml: string): string {
  const doc = parse(catalog_yaml) as Record<
    string,
    { codes?: Record<string, CatalogEntry> } | undefined
  >;
  const codes = doc["x-error-catalog"]?.codes;
  if (codes === undefined) throw new Error("x-error-catalog.codes missing");
  const names = Object.keys(codes);
  if (names.length !== 36)
    throw new Error(`expected 36 error codes, found ${names.length}`);
  const lines: string[] = [];
  const retry: string[] = [];
  for (const name of names) {
    const entry = codes[name];
    const status = entry?.status;
    if (typeof status !== "number" || !Number.isInteger(status))
      throw new Error(`no integer status for ${name}`);
    lines.push(`  ${JSON.stringify(name)}: ${status},`);
    if (entry?.retry_after === true) retry.push(JSON.stringify(name));
  }
  return [
    "// GENERATED by `npm run gen:error-status` from x-error-catalog in docs/contracts/interface.openapi.yaml. Do not edit.",
    "export const ERROR_STATUS = {",
    ...lines,
    "} as const;",
    `export const RETRY_AFTER_CODES = [${retry.join(", ")}] as const;`,
    "",
  ].join("\n");
}

if (import.meta.url === pathToFileURL(process.argv[1] ?? "").href) {
  const yaml_path = fileURLToPath(
    new URL("../../../docs/contracts/interface.openapi.yaml", import.meta.url),
  );
  const out_path = fileURLToPath(
    new URL("../src/server/http/error-status.generated.ts", import.meta.url),
  );
  writeFileSync(out_path, render_error_status(readFileSync(yaml_path, "utf8")));
}
