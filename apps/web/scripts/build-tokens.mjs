// Generates src/styles/tokens.css from the `json tokens` block of docs/design/design.md.
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath, pathToFileURL } from "node:url";

const here = path.dirname(fileURLToPath(import.meta.url));
export const DESIGN_PATH = path.resolve(here, "../../../docs/design/design.md");
export const OUT_PATH = path.resolve(here, "../src/styles/tokens.css");

/**
 * @param {string} markdown
 * @returns {any}
 */
export function extractTokens(markdown) {
  const blocks = [...markdown.matchAll(/```json tokens\n([\s\S]*?)\n```/g)];
  if (blocks.length !== 1) {
    throw new Error("design.md: expected exactly one json tokens block");
  }
  return JSON.parse(blocks[0][1]);
}

const kebab = (/** @type {string} */ k) => k.replace(/[A-Z]/g, (c) => "-" + c.toLowerCase());
const px = (/** @type {number} */ n) => (n === 0 ? "0px" : `${n}px`);

/** @param {Record<string,string>} obj @param {string} prefix */
function colorLines(obj) {
  return Object.entries(obj).map(([k, v]) => `--color-${k}: ${v};`);
}
/** @param {Record<string,string>} obj */
function shadowLines(obj) {
  return Object.entries(obj).map(([k, v]) => `--shadow-${k}: ${v};`);
}

/**
 * @param {any} t
 * @returns {string}
 */
export function buildTokensCss(t) {
  const ind = (/** @type {string[]} */ lines, n = 2) =>
    lines.map((l) => " ".repeat(n) + l).join("\n");

  const theme = [];
  theme.push("--color-*: initial;");
  theme.push(...colorLines(t.colors.light));
  theme.push(`--font-sans: ${t.type.family.sans};`);
  theme.push(`--font-mono: ${t.type.family.mono};`);
  for (const [k, v] of Object.entries(t.type.weight)) theme.push(`--font-weight-${k}: ${v};`);
  for (const [k, s] of Object.entries(t.type.scale)) {
    theme.push(`--text-${k}: ${s.size}px;`);
    theme.push(`--text-${k}--line-height: ${s.lineHeight};`);
    theme.push(`--text-${k}--font-weight: ${s.weight};`);
    theme.push(`--text-${k}--letter-spacing: ${s.tracking ?? "0"};`);
  }
  theme.push(`--measure-reading: ${t.type.measure.reading};`);
  for (const [k, v] of Object.entries(t.space)) theme.push(`--space-${k.replace(/\./g, "_")}: ${px(v)};`);
  for (const [k, v] of Object.entries(t.spaceSemantic)) theme.push(`--sem-${k}: ${px(v)};`);
  for (const [k, v] of Object.entries(t.control.height)) theme.push(`--control-${k}: ${px(v)};`);
  for (const [k, v] of Object.entries(t.radius)) theme.push(`--radius-${k}: ${px(v)};`);
  for (const [k, v] of Object.entries(t.border.width)) theme.push(`--border-width-${k}: ${px(v)};`);
  theme.push(`--focus-offset: ${px(t.border.focusOffset)};`);
  theme.push(...shadowLines(t.elevation.light));
  for (const [k, v] of Object.entries(t.motion.duration)) theme.push(`--duration-${kebab(k)}: ${v}ms;`);
  theme.push(`--duration-fade-reduced: ${t.motion.reducedMotion.opacityFadeMax}ms;`);
  for (const [k, v] of Object.entries(t.motion.easing)) theme.push(`--ease-${k}: ${v};`);
  for (const [k, v] of Object.entries(t.z)) theme.push(`--z-${k}: ${v};`);
  for (const [k, v] of Object.entries(t.breakpoints)) theme.push(`--breakpoint-${k}: ${px(v)};`);
  for (const [k, v] of Object.entries(t.layout)) theme.push(`--layout-${k}: ${px(v)};`);

  const dark = [...colorLines(t.colors.dark), ...shadowLines(t.elevation.dark)];

  return (
    `/* GENERATED by scripts/build-tokens.mjs from docs/design/design.md (tokens ${t.name} ${t.version}). Do not edit; run \`npm run tokens\`. */\n\n` +
    `@theme static {\n${ind(theme)}\n}\n\n` +
    `:root {\n  color-scheme: light dark;\n}\n\n` +
    `[data-theme="light"] {\n  color-scheme: light;\n}\n\n` +
    `[data-theme="dark"] {\n  color-scheme: dark;\n${ind(dark)}\n}\n\n` +
    `@media (prefers-color-scheme: dark) {\n  :root:not([data-theme]) {\n${ind(dark, 4)}\n  }\n}\n\n` +
    `@media (prefers-reduced-motion: reduce) {\n  :root {\n    --duration-fast: 0ms;\n    --duration-base: 0ms;\n    --duration-slow: 0ms;\n  }\n}\n`
  );
}

export function main() {
  const md = fs.readFileSync(DESIGN_PATH, "utf8");
  const css = buildTokensCss(extractTokens(md));
  fs.mkdirSync(path.dirname(OUT_PATH), { recursive: true });
  fs.writeFileSync(OUT_PATH, css);
  console.log(`wrote ${OUT_PATH}`);
}

if (process.argv[1] && import.meta.url === pathToFileURL(process.argv[1]).href) main();
